#!/usr/bin/env node
import fs from 'fs'
import path from 'path'
import bcrypt from 'bcryptjs'

// Configuration: adjust numbers here
const RESOURCES_COUNT = 80
const PROJECTS = [
  { nome: 'Portal Cliente', categoria: 'Web', descricao: 'Portal para clientes', inicio: '2024-01-15', fim: '2024-10-01', orcamento: 250000.00 },
  { nome: 'App Mobile V2', categoria: 'Mobile', descricao: 'Nova versão do app', inicio: '2024-03-01', fim: '2024-12-15', orcamento: 180000.00 },
  { nome: 'Migração Cloud', categoria: 'Infra', descricao: 'Migração para cloud', inicio: '2024-05-01', fim: '2024-11-30', orcamento: 400000.00 },
  { nome: 'ERP Upgrade', categoria: 'ERP', descricao: 'Atualização do ERP', inicio: '2024-02-01', fim: '2024-09-30', orcamento: 320000.00 },
  { nome: 'Site Marketing', categoria: 'Marketing', descricao: 'Refatoração do site', inicio: '2024-04-01', fim: '2024-08-15', orcamento: 60000.00 },
]

const firstNames = ['Pedro','Ana','João','Mariana','Lucas','Carolina','Rafael','Bruna','Marcos','Paula','Gustavo','Laura','Felipe','Camila','Eduardo','Sofia','Thiago','Beatriz','Victor','Mariana']
const lastNames = ['Silva','Santos','Oliveira','Pereira','Rodrigues','Almeida','Costa','Gomes','Martins','Lima','Araújo','Fernandes','Barbosa','Ribeiro','Cardoso']

function randInt(min,max){return Math.floor(Math.random()*(max-min+1))+min}
function pick(arr){return arr[Math.floor(Math.random()*arr.length)]}
function makeName(i){const fn=pick(firstNames); const ln1=pick(lastNames); const ln2=pick(lastNames); return `${fn} ${ln1} ${ln2}${i>0? ' '+i: ''}`}
function emailFor(name,i){const base = name.toLowerCase().replace(/[^a-z0-9]+/g,'.'); return `${base}${i}@pam.local`}

function makeUsers(n){
  const users=[]
  for(let i=0;i<n;i++){ const name=makeName(i); const email=emailFor(name,i); users.push({name,email}) }
  return users
}

function buildSql() {
  const manager = { name: 'Gestor Único', email: 'gestor.unico@pam.local', first: 'gestor' }
  const resources = makeUsers(RESOURCES_COUNT)

  const lines = []
  lines.push("USE PAM;")
  lines.push('-- Seed generated by generate_seed_sql.js')
  lines.push('START TRANSACTION;')

  // manager
  const mgrPass = manager.first + '123'
  const mgrHash = bcrypt.hashSync(mgrPass, 12)
  lines.push(`INSERT INTO FUNCIONARIO (NOME, MATRICULA, IDADE, EMAIL, SENHA, DEPARTAMENTO, CARGO, TIPO_PERFIL, GESTOR, ATIVO)
SELECT * FROM (SELECT '${manager.name.replace(/'/g,"''")}' AS NOME, NULL AS MATRICULA, 42 AS IDADE, '${manager.email}' AS EMAIL, '${mgrHash}' AS SENHA, 'Gestão' AS DEPARTAMENTO, 'Gerente de Projetos' AS CARGO, 'gestor' AS TIPO_PERFIL, 1 AS GESTOR, 1 AS ATIVO) AS tmp
WHERE NOT EXISTS (SELECT 1 FROM FUNCIONARIO WHERE EMAIL = '${manager.email}');`)

  // resources
  resources.forEach((u, idx)=>{
    const first = String(u.name).split(' ')[0].toLowerCase()
    const plain = first + '123'
    const hash = bcrypt.hashSync(plain, 12)
    const safeName = u.name.replace(/'/g,"''")
    lines.push(`INSERT INTO FUNCIONARIO (NOME, MATRICULA, IDADE, EMAIL, SENHA, DEPARTAMENTO, CARGO, TIPO_PERFIL, GESTOR, FK_GESTOR_ID, ATIVO)
SELECT * FROM (SELECT '${safeName}' AS NOME, NULL AS MATRICULA, ${randInt(22,45)} AS IDADE, '${u.email}' AS EMAIL, '${hash}' AS SENHA, 'Desenvolvimento' AS DEPARTAMENTO, 'Recurso' AS CARGO, 'recurso' AS TIPO_PERFIL, 0 AS GESTOR, (SELECT ID FROM FUNCIONARIO WHERE EMAIL = '${manager.email}' LIMIT 1) AS FK_GESTOR_ID, 1 AS ATIVO) AS tmp
WHERE NOT EXISTS (SELECT 1 FROM FUNCIONARIO WHERE EMAIL = '${u.email}');`)
  })

  // projects
  PROJECTS.forEach(p=>{
    const safeName = p.nome.replace(/'/g,"''")
    const safeDesc = p.descricao.replace(/'/g,"''")
    lines.push(`INSERT INTO PROJETOS (NOME, CATEGORIA, DESCRICAO, STATUS, GESTOR_ID, DATA_INICIO, DATA_ESTIMADA_FIM, ORCAMENTO)
SELECT * FROM (SELECT '${safeName}' AS NOME, '${p.categoria}' AS CATEGORIA, '${safeDesc}' AS DESCRICAO, 'andamento' AS STATUS, (SELECT ID FROM FUNCIONARIO WHERE EMAIL = '${manager.email}' LIMIT 1) AS GESTOR_ID, '${p.inicio}' AS DATA_INICIO, '${p.fim}' AS DATA_ESTIMADA_FIM, ${p.orcamento} AS ORCAMENTO) AS tmp
WHERE NOT EXISTS (SELECT 1 FROM PROJETOS WHERE NOME = '${safeName}');`)
  })

  // fetch project ids via SQL later not needed here; create sample marcos/entregas generically referencing projects by name
  PROJECTS.forEach(p=>{
    const pName = p.nome.replace(/'/g,"''")
    const milestones = randInt(3,5)
    for(let m=1;m<=milestones;m++){
      const title = `Marco ${m} - ${p.nome}`.replace(/'/g,"''")
      const due = `2024-${String(randInt(6,12)).padStart(2,'0')}-${String(randInt(5,28)).padStart(2,'0')}`
      const total = randInt(2,6)
      const completed = Math.floor(total*Math.random())
      const status = completed >= total ? 'Concluído' : (completed>0 ? 'Andamento' : 'Pendente')
      lines.push(`INSERT INTO MARCO (PROJETO_ID, TITULO, DESCRICAO, DATA_VENCIMENTO, TOTAL_ENTREGAS, ENTREGAS_CONCLUIDAS, STATUS)
SELECT * FROM (SELECT (SELECT ID FROM PROJETOS WHERE NOME = '${pName}' LIMIT 1) AS PROJETO_ID, '${title}' AS TITULO, '${title}' AS DESCRICAO, '${due}' AS DATA_VENCIMENTO, ${total} AS TOTAL_ENTREGAS, ${completed} AS ENTREGAS_CONCLUIDAS, '${status}' AS STATUS) AS tmp
WHERE NOT EXISTS (SELECT 1 FROM MARCO m JOIN PROJETOS pr ON pr.ID = m.PROJETO_ID WHERE pr.NOME = '${pName}' AND m.TITULO = '${title}');`)
      // deliveries
      for(let d=1; d<=total; d++){
        const t = `Entrega ${d} - Marco ${m} - ${p.nome}`.replace(/'/g,"''")
        const entregStatus = d<=completed ? 'concluida' : 'pendente'
        const data_ent = d<=completed ? due : null
        lines.push(`INSERT INTO ENTREGA (MARCO_ID, TITULO, DESCRICAO, STATUS, DATA_ENTREGA)
SELECT * FROM (SELECT (SELECT m.ID FROM MARCO m JOIN PROJETOS pr ON pr.ID = m.PROJETO_ID WHERE pr.NOME = '${pName}' AND m.TITULO = '${title}' LIMIT 1) AS MARCO_ID, '${t}' AS TITULO, '${t}' AS DESCRICAO, '${entregStatus}' AS STATUS, ${data_ent ? `'${data_ent}'` : 'NULL'} AS DATA_ENTREGA) AS tmp
WHERE NOT EXISTS (SELECT 1 FROM ENTREGA e JOIN MARCO m ON m.ID = e.MARCO_ID JOIN PROJETOS pr ON pr.ID = m.PROJETO_ID WHERE pr.NOME='${pName}' AND m.TITULO='${title}' AND e.TITULO='${t}');`)
      }
    }
  })

  // allocations: allocate each resource to 1-3 random projects
  lines.push('-- Allocations: distribute resources across projects')
  lines.push("-- This section creates allocations by selecting existing users and projects")
  lines.push("-- NOTE: run after the projects/users exist")
  lines.push("SET @i = 0;")
  lines.push("SELECT ID INTO @tmp FROM PROJETOS LIMIT 1;")
  // We'll add an insert loop via client-side convenience: but SQL-only loops are painful; instead create generic inserts for first N resources
  // Simpler: create allocations for first 30 resources across first 6 projects
  lines.push("-- Create a sample of allocations")
  for(let r=0;r<Math.min(30, RESOURCES_COUNT); r++){
    const projIndex = r % PROJECTS.length
    const projName = PROJECTS[projIndex].nome.replace(/'/g,"''")
    lines.push(`INSERT INTO ALOCACOES_PROJETO (PROJETO_ID, USUARIO_ID, PERCENTUAL_ALOCACAO, DATA_INICIO, STATUS)
SELECT * FROM (SELECT (SELECT ID FROM PROJETOS WHERE NOME = '${projName}' LIMIT 1) AS PROJETO_ID, (SELECT ID FROM FUNCIONARIO WHERE EMAIL = (SELECT EMAIL FROM (SELECT EMAIL FROM FUNCIONARIO WHERE TIPO_PERFIL='recurso' LIMIT ${r},1) as sub) LIMIT 1) AS USUARIO_ID, ${[50,75,100][r%3] } AS PERCENTUAL_ALOCACAO, '2024-01-01' AS DATA_INICIO, 'ativo' AS STATUS) as tmp
WHERE NOT EXISTS (SELECT 1 FROM ALOCACOES_PROJETO a JOIN FUNCIONARIO f ON f.ID = a.USUARIO_ID WHERE a.PROJETO_ID = (SELECT ID FROM PROJETOS WHERE NOME = '${projName}' LIMIT 1) AND f.EMAIL = (SELECT EMAIL FROM (SELECT EMAIL FROM FUNCIONARIO WHERE TIPO_PERFIL='recurso' LIMIT ${r},1) as sub));`)
  }

  // Time entries: create several lancamentos_horas per project
  lines.push('-- Time entries (lancamentos_horas)')
  PROJECTS.forEach((p, pj) => {
    const pName = p.nome.replace(/'/g,"''")
    const entriesPerProject = 12
    for (let e = 0; e < entriesPerProject; e++) {
      // pick a resource by offset to spread users
      const userOffset = (pj * entriesPerProject + e) % RESOURCES_COUNT
      const minutes = [30,60,90,120,180,240,300][Math.floor(Math.random()*7)]
      const status = (Math.random() < 0.8) ? 'aprovado' : 'pendente'
      // random date between project.start and project.end approx — use month numbers for simplicity
      const startMonth = Number(p.inicio.split('-')[1]) || 1
      const endMonth = Number(p.fim.split('-')[1]) || 12
      const month = String(randInt(startMonth, endMonth)).padStart(2,'0')
      const day = String(randInt(1,28)).padStart(2,'0')
      const date = `2024-${month}-${day}`
      const desc = `Horas apontadas - ${p.nome} - ${e+1}`.replace(/'/g,"''")
      lines.push(`INSERT INTO LANCAMENTOS_HORAS (USUARIO_ID, PROJETO_ID, DESCRICAO_ATIVIDADE, CATEGORIA, DURACAO_MINUTOS, DATA_LANCAMENTO, STATUS)
SELECT * FROM (SELECT (SELECT ID FROM FUNCIONARIO WHERE TIPO_PERFIL='recurso' LIMIT ${userOffset},1) AS USUARIO_ID, (SELECT ID FROM PROJETOS WHERE NOME = '${pName}' LIMIT 1) AS PROJETO_ID, '${desc}' AS DESCRICAO_ATIVIDADE, 'desenvolvimento' AS CATEGORIA, ${minutes} AS DURACAO_MINUTOS, '${date}' AS DATA_LANCAMENTO, '${status}' AS STATUS) AS tmp
WHERE NOT EXISTS (SELECT 1 FROM LANCAMENTOS_HORAS l JOIN FUNCIONARIO f ON f.ID = l.USUARIO_ID JOIN PROJETOS pr ON pr.ID = l.PROJETO_ID WHERE f.TIPO_PERFIL='recurso' AND pr.NOME='${pName}' AND l.DESCRICAO_ATIVIDADE='${desc}' AND l.DATA_LANCAMENTO='${date}');`)
    }
  })

  // Hour extra requests: create SOLITICACAO rows for a subset of resources
  lines.push('-- Hora extra solicitacoes')
  const overtimeRequests = Math.max(5, Math.floor(RESOURCES_COUNT * 0.12))
  for (let i=0;i<overtimeRequests;i++) {
    const userOffset = i % RESOURCES_COUNT
    const horas = randInt(1,6)
    const startDate = `2024-${String(randInt(6,11)).padStart(2,'0')}-${String(randInt(1,28)).padStart(2,'0')}`
    const endDate = startDate
    const motivo = `Solicitação de hora extra (${horas}h)`
    lines.push(`INSERT INTO SOLITICACAO (USUARIO_ID, TIPO, HORAS, DATA_INICIO, DATA_FIM, MOTIVO, STATUS)
SELECT * FROM (SELECT (SELECT ID FROM FUNCIONARIO WHERE TIPO_PERFIL='recurso' LIMIT ${userOffset},1) AS USUARIO_ID, 'hora_extra' AS TIPO, ${horas} AS HORAS, '${startDate}' AS DATA_INICIO, '${endDate}' AS DATA_FIM, '${motivo.replace(/'/g,"''")}' AS MOTIVO, 'pendente' AS STATUS) AS tmp
WHERE NOT EXISTS (SELECT 1 FROM SOLITICACAO s JOIN FUNCIONARIO f ON f.ID = s.USUARIO_ID WHERE f.TIPO_PERFIL='recurso' AND s.DATA_INICIO='${startDate}' AND s.HORAS=${horas} AND s.TIPO='hora_extra');`)
  }

  lines.push('COMMIT;')
  return lines.join('\n')
}

const out = buildSql()
const outPath = path.resolve(process.cwd(), 'src', 'database', 'seed.sql')
fs.writeFileSync(outPath, out)
console.log('Wrote seed SQL to', outPath)
