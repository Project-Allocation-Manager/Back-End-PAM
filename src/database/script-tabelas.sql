-- Script de criação do schema do PAM
-- Rodar em um banco MySQL (charset utf8mb4)

CREATE DATABASE IF NOT EXISTS PAM CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE PAM;

-- Tabela funcionario
CREATE TABLE IF NOT EXISTS FUNCIONARIO (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  NOME VARCHAR(255) NOT NULL,
  MATRICULA VARCHAR(50) DEFAULT NULL,
  IDADE INT DEFAULT NULL,
  EMAIL VARCHAR(255) NOT NULL,
  SENHA VARCHAR(255) DEFAULT NULL,
  DEPARTAMENTO VARCHAR(100) DEFAULT NULL,
  CARGO VARCHAR(100) DEFAULT NULL,
  TIPO_PERFIL ENUM('admin','gestor','recurso') NOT NULL DEFAULT 'recurso',
  GESTOR BOOLEAN DEFAULT FALSE,
  FK_GESTOR_ID INT DEFAULT NULL,
  ATIVO BOOLEAN DEFAULT TRUE,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_funcionario_email (EMAIL),
  UNIQUE KEY uk_funcionario_matricula (MATRICULA),
  INDEX idx_funcionario_nome (NOME),
  FOREIGN KEY (FK_GESTOR_ID) REFERENCES FUNCIONARIO(ID) ON DELETE SET NULL
);

-- Tabela projetos
CREATE TABLE IF NOT EXISTS PROJETOS (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  NOME VARCHAR(255) NOT NULL,
  CATEGORIA VARCHAR(100) DEFAULT NULL,
  DESCRICAO TEXT DEFAULT NULL,
  STATUS ENUM('planejamento','andamento','pausado','concluido','cancelado') DEFAULT 'planejamento',
  GESTOR_ID INT DEFAULT NULL,
  DATA_INICIO DATE DEFAULT NULL,
  DATA_ESTIMADA_FIM DATE DEFAULT NULL,
  DATA_FIM DATE DEFAULT NULL,
  ORCAMENTO DECIMAL(14,2) DEFAULT NULL,
  PROGRESSO DECIMAL(5,2) DEFAULT 0,
  ATIVO BOOLEAN DEFAULT TRUE,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_projetos_nome (NOME),
  INDEX idx_projetos_status (STATUS),
  FOREIGN KEY (GESTOR_ID) REFERENCES FUNCIONARIO(ID) ON DELETE SET NULL
);

-- Tabela alocacoes_projeto
CREATE TABLE IF NOT EXISTS ALOCACOES_PROJETO (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  PROJETO_ID INT NOT NULL,
  USUARIO_ID INT NOT NULL,
  PERCENTUAL_ALOCACAO DECIMAL(5,2) NOT NULL DEFAULT 100.00,
  DURACAO_ALOCACAO INT DEFAULT NULL,
  DATA_INICIO DATE NOT NULL,
  DATA_FIM DATE DEFAULT NULL,
  IS_EMPRESTADO BOOLEAN DEFAULT FALSE,
  GESTOR_ORIGEM_ID INT DEFAULT NULL,
  GESTOR_DESTINO_ID INT DEFAULT NULL,
  MOTIVO_EMPRESTIMO TEXT DEFAULT NULL,
  STATUS VARCHAR(50) DEFAULT 'ativo',
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_alocacoes_projeto_projeto (PROJETO_ID),
  INDEX idx_alocacoes_projeto_usuario (USUARIO_ID),
  FOREIGN KEY (PROJETO_ID) REFERENCES PROJETOS(ID) ON DELETE CASCADE,
  FOREIGN KEY (USUARIO_ID) REFERENCES FUNCIONARIO(ID) ON DELETE CASCADE
);

-- Tabela lancamentos_horas
CREATE TABLE IF NOT EXISTS LANCAMENTOS_HORAS (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  USUARIO_ID INT NOT NULL,
  PROJETO_ID INT NOT NULL,
  DESCRICAO_ATIVIDADE TEXT NOT NULL,
  CATEGORIA ENUM('desenvolvimento','reuniao','daily','teste','discovery','planejamento','homologacao','documentacao','outros') DEFAULT 'desenvolvimento',
  DURACAO_MINUTOS INT NOT NULL,
  DURACAO INT DEFAULT NULL,
  DATA_LANCAMENTO DATE NOT NULL,
  HORA_INICIO TIME DEFAULT NULL,
  HORA_FIM TIME DEFAULT NULL,
  STATUS ENUM('pendente','aprovado','reprovado') DEFAULT 'pendente',
  OBSERVACAO_APROVACAO TEXT DEFAULT NULL,
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_lancamentos_usuario (USUARIO_ID),
  INDEX idx_lancamentos_projeto (PROJETO_ID),
  INDEX idx_lancamentos_data (DATA_LANCAMENTO),
  FOREIGN KEY (USUARIO_ID) REFERENCES FUNCIONARIO(ID) ON DELETE CASCADE,
  FOREIGN KEY (PROJETO_ID) REFERENCES PROJETOS(ID) ON DELETE CASCADE
);

-- Tabela solicitacao
CREATE TABLE IF NOT EXISTS SOLITICACAO (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  USUARIO_ID INT NOT NULL,
  TIPO ENUM('ausencia','hora_extra') NOT NULL,
  TIPO_AUSENCIA VARCHAR(100) DEFAULT NULL,
  DATA_INICIO DATE DEFAULT NULL,
  DATA_FIM DATE DEFAULT NULL,
  HORAS INT DEFAULT NULL,
  MOTIVO TEXT DEFAULT NULL,
  STATUS ENUM('pendente','aprovado','reprovado') DEFAULT 'pendente',
  APROVADO_POR INT DEFAULT NULL,
  OBSERVACAO_APROVACAO TEXT DEFAULT NULL,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_solicitacao_usuario (USUARIO_ID),
  FOREIGN KEY (USUARIO_ID) REFERENCES FUNCIONARIO(ID) ON DELETE CASCADE
);

-- Tabela marco
CREATE TABLE IF NOT EXISTS MARCO (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  PROJETO_ID INT NOT NULL,
  TITULO VARCHAR(255) NOT NULL,
  DESCRICAO TEXT DEFAULT NULL,
  DATA_VENCIMENTO DATE DEFAULT NULL,
  STATUS VARCHAR(50) DEFAULT 'Pendente',
  TOTAL_ENTREGAS INT DEFAULT 0,
  ENTREGAS_CONCLUIDAS INT DEFAULT 0,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (PROJETO_ID) REFERENCES PROJETOS(ID) ON DELETE CASCADE
);

-- Tabela entrega
CREATE TABLE IF NOT EXISTS ENTREGA (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  MARCO_ID INT NOT NULL,
  TITULO VARCHAR(255) NOT NULL,
  DESCRICAO TEXT DEFAULT NULL,
  STATUS VARCHAR(50) DEFAULT 'pendente',
  DATA_ENTREGA DATE DEFAULT NULL,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (MARCO_ID) REFERENCES MARCO(ID) ON DELETE CASCADE
);

-- Tabela auditoria
CREATE TABLE IF NOT EXISTS AUDITORIA (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  USUARIO_ID INT DEFAULT NULL,
  ENTIDADE VARCHAR(100) DEFAULT NULL,
  ENTIDADE_ID INT DEFAULT NULL,
  ACAO VARCHAR(50) DEFAULT NULL,
  DADOS_ANTERIORES JSON DEFAULT NULL,
  DADOS_NOVOS JSON DEFAULT NULL,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (USUARIO_ID) REFERENCES FUNCIONARIO(ID) ON DELETE SET NULL
);
