  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS LANCAMENTOS_HORAS (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  USUARIO_ID INT NOT NULL,
  PROJETO_ID INT NOT NULL,
  DESCRICAO_ATIVIDADE TEXT NOT NULL,
  CATEGORIA ENUM('desenvolvimento','reuniao','daily','teste','discovery','planejamento','homologacao','documentacao','outros') DEFAULT 'desenvolvimento',
  DURACAO_MINUTOS INT NOT NULL,
  DURACAO INT DEFAULT NULL,
  DATA_LANCAMENTO DATE NOT NULL,
  HORA_INICIO TIME DEFAULT NULL,
  HORA_FIM TIME DEFAULT NULL,
  STATUS ENUM('pendente','aprovado','reprovado') DEFAULT 'pendente',
  OBSERVACAO_APROVACAO TEXT DEFAULT NULL,
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS SOLITICACAO (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  USUARIO_ID INT NOT NULL,
